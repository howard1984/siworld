const FIRST_TRANSITION_SEQUENCE: u64 = 83065;

pub fn release_roster(binding: Binding) -> Result<Option<Roster>, String> {
    if binding.network != NETWORK || binding.genesis != GENESIS || binding.verifier != VERIFIER {
        return Ok(None);
    }
    Roster::with_transition(
        binding,
        [AUTHORITY_0, AUTHORITY_1],
        AUTHORITY_2,
        FIRST_TRANSITION_SEQUENCE,
    )
    .map(Some)
}

#[cfg(test)]
mod tests {
    use super::*;
    use sha2::Digest;

    #[test]
    fn engineering_roster_pins_registered_key_and_transition_boundary() {
        let binding = Binding {
            network: NETWORK,
            genesis: GENESIS,
            verifier: VERIFIER,
        };
        let key_digest: [u8; 32] = sha2::Sha256::digest(AUTHORITY_2).into();
        assert_eq!(
            key_digest,
            [
                0xc2, 0x68, 0x3a, 0x11, 0xcb, 0x0c, 0x57, 0x25, 0x4f, 0x70, 0x33, 0x6c, 0x3a, 0x6c,
                0xb2, 0x3c, 0x20, 0x38, 0xf7, 0x0d, 0x9d, 0x6c, 0x8e, 0x46, 0x57, 0xae, 0x6a, 0xce,
                0xc7, 0xda, 0xab, 0xde,
            ]
        );
        let legacy = Roster::new(binding, [AUTHORITY_0, AUTHORITY_1]).unwrap();
        let roster = release_roster(binding).unwrap().unwrap();
        assert_eq!(
            roster.digest_for_sequence(FIRST_TRANSITION_SEQUENCE - 1),
            legacy.digest()
        );
        assert_ne!(
            roster.digest_for_sequence(FIRST_TRANSITION_SEQUENCE),
            legacy.digest()
        );
        assert!(
            roster
                .index_for_sequence(&AUTHORITY_2, FIRST_TRANSITION_SEQUENCE - 1)
                .is_err()
        );
        assert_eq!(
            roster.index_for_sequence(&AUTHORITY_2, FIRST_TRANSITION_SEQUENCE),
            Ok(2)
        );
        assert_eq!(
            roster.admission_first_sequence((FIRST_TRANSITION_SEQUENCE - 1) * 21600),
            Ok(FIRST_TRANSITION_SEQUENCE)
        );
        assert!(
            roster
                .admission_first_sequence(FIRST_TRANSITION_SEQUENCE * 21600)
                .is_err()
        );
    }

    #[test]
    fn engineering_roster_requires_the_complete_release_binding() {
        let binding = Binding {
            network: NETWORK,
            genesis: GENESIS,
            verifier: VERIFIER,
        };
        assert!(release_roster(binding).unwrap().is_some());
        for field in 0..3 {
            let mut changed = binding;
            match field {
                0 => changed.network[0] ^= 1,
                1 => changed.genesis[0] ^= 1,
                _ => changed.verifier[0] ^= 1,
            }
            assert!(release_roster(changed).unwrap().is_none());
        }
        assert_ne!(AUTHORITY_0, AUTHORITY_1);
    }
}
